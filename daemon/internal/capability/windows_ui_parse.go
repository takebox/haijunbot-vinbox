package capability

// This file holds the pure logic of the Windows UI automation capabilities
// (windows.ui.tree / windows.ui.menu): PowerShell script construction and output parsing.
//
// These functions only depend on the standard library and encodePowerShellText (defined in the build-tag-free
// windows_gui_parse.go), and do not reference any platform-specific types, so they **carry no build tags**:
// this way they can be compiled and directly unit-tested on Linux / macOS, so that even without a Windows environment
// the "script structure is complete, user input is correctly escaped, output is parsed correctly" can still be verified.
//
// The accompanying tests are in windows_ui_parse_test.go; windows_ui_windows.go, which carries the //go:build windows tag,
// is responsible for registering the capabilities, parsing parameters, and invoking runWindowsPowerShellCommand.
//
// Security convention: any string coming from user input (title, menu path segments) is uniformly escaped by
// encodePowerShellText into a single-quoted literal before being concatenated into the script, never concatenated directly.

import (
	"fmt"
	"strconv"
	"strings"
)

// uiTreeMaxDepthDefault is the default maximum depth of the control tree.
const uiTreeMaxDepthDefault = 10

// uiTreeMaxControlsDefault is the default maximum number of controls in the control tree.
const uiTreeMaxControlsDefault = 200

// windowsUIAddTypePreamble is the preamble that loads the UIAutomation assemblies.
// UIAutomationClient/UIAutomationTypes are built-in assemblies of the .NET Framework,
// which Windows PowerShell 5.1 can load directly via Add-Type, with zero third-party dependencies.
const windowsUIAddTypePreamble = "Add-Type -AssemblyName UIAutomationClient; Add-Type -AssemblyName UIAutomationTypes"

// buildWindowsUITreeScript constructs the PowerShell script for windows.ui.tree.
//
// At least one of windowID and title is provided to locate the target window:
//   - when windowID is non-empty, use FromHandle([IntPtr]) to locate directly (decimal or 0x hexadecimal);
//   - otherwise use title substring matching to find the window handle.
//
// maxDepth / maxControls limit the traversal scale, preventing a hang on a large window.
// The script outputs controls as "|"-separated text lines (depth|type|name|automation_id|x|y|w|h),
// parsed by parseWindowsUITreeText.
func buildWindowsUITreeScript(windowID, title string, maxDepth, maxControls int) (string, error) {
	if windowID == "" && title == "" {
		return "", fmt.Errorf("at least one of the parameters window_id and title must be provided")
	}
	if maxDepth < 1 {
		maxDepth = uiTreeMaxDepthDefault
	}
	if maxControls < 1 {
		maxControls = uiTreeMaxControlsDefault
	}

	var rootExpr string
	if windowID != "" {
		// window_id is an integer (decimal or 0x hexadecimal), formatted directly, with no injection surface.
		rootExpr = "[System.Windows.Automation.AutomationElement]::FromHandle([IntPtr]" + windowID + ")"
	} else {
		// title is escaped by encodePowerShellText into a single-quoted literal, then concatenated with the wildcard into a -like pattern.
		quotedTitle := encodePowerShellText(title)
		rootExpr = "$w = Get-Process | Where-Object { $_.MainWindowTitle -like ('*' + " + quotedTitle + " + '*') } | Select-Object -First 1; " +
			"if ($w -eq $null) { Write-Output 'ERROR:no-window'; exit }; " +
			"[System.Windows.Automation.AutomationElement]::FromHandle([IntPtr]$w.MainWindowHandle)"
	}

	return windowsUIAddTypePreamble + "; " +
		"$root = " + rootExpr + "; " +
		"if ($root -eq $null) { Write-Output 'ERROR:no-window'; exit }; " +
		"$sb = New-Object System.Text.StringBuilder; $script:count = 0; " +
		"function Walk($el, $depth) { " +
		"if ($script:count -ge " + strconv.Itoa(maxControls) + ") { return }; " +
		"$t = $el.Current.ControlType.ProgrammaticName; " +
		"$n = $el.Current.Name; " +
		"$a = $el.Current.AutomationId; " +
		"$r = $el.Current.BoundingRectangle; " +
		"[void]$script:sb.AppendLine(\"$depth|$t|$n|$a|$($r.X)|$($r.Y)|$($r.Width)|$($r.Height)\"); " +
		"$script:count++; " +
		"if ($depth -ge " + strconv.Itoa(maxDepth) + ") { return }; " +
		"$children = $el.FindAll([System.Windows.Automation.TreeScope]::Children, [System.Windows.Automation.Condition]::TrueCondition); " +
		"foreach ($c in $children) { Walk $c ($depth + 1) } }; " +
		"Walk $root 0; $script:sb.ToString()", nil
}

// parseWindowsUITreeText parses the control tree text output into a list of controls.
//
// Each line format: depth|type|name|automation_id|x|y|w|h (generated by buildWindowsUITreeScript).
// Returns the control entries arranged in traversal order, with fields depth/type/name/automation_id/rect.
func parseWindowsUITreeText(out string) []map[string]any {
	controls := make([]map[string]any, 0, 64)
	lines := strings.Split(strings.ReplaceAll(out, "\r\n", "\n"), "\n")
	for _, line := range lines {
		line = strings.TrimSpace(line)
		if line == "" {
			continue
		}
		// Skip error marker lines (such as ERROR:no-window).
		if strings.HasPrefix(line, "ERROR:") {
			continue
		}
		parts := strings.Split(line, "|")
		if len(parts) < 8 {
			continue
		}
		controls = append(controls, map[string]any{
			"depth":         strings.TrimSpace(parts[0]),
			"type":          strings.TrimSpace(parts[1]),
			"name":          strings.TrimSpace(parts[2]),
			"automation_id": strings.TrimSpace(parts[3]),
			"rect": map[string]any{
				"x":      strings.TrimSpace(parts[4]),
				"y":      strings.TrimSpace(parts[5]),
				"width":  strings.TrimSpace(parts[6]),
				"height": strings.TrimSpace(parts[7]),
			},
		})
	}
	return controls
}

// parseWindowsUIMenuPath parses a menu path string into a list of menu item names.
//
// Syntax: separated by "->", such as "File->Open", "Edit->Copy". A single segment "Help" is also supported.
// Returns the list of segments after removing leading/trailing whitespace; an empty path returns an error.
func parseWindowsUIMenuPath(path string) ([]string, error) {
	trimmed := strings.TrimSpace(path)
	if trimmed == "" {
		return nil, fmt.Errorf("parameter path cannot be empty")
	}
	raw := strings.Split(trimmed, "->")
	segments := make([]string, 0, len(raw))
	for _, s := range raw {
		s = strings.TrimSpace(s)
		if s == "" {
			return nil, fmt.Errorf("parameter path has an invalid format %q, neither side of '->' can be empty", path)
		}
		segments = append(segments, s)
	}
	return segments, nil
}

// buildWindowsUIMenuScript constructs the PowerShell script for windows.ui.menu.
//
// At least one of windowID and title is provided to locate the target window (same as tree).
// path is the menu path, such as "File->Open". The script uses UIA to find the menu item level by level:
//   - the first N-1 segments: after finding the element, try ExpandCollapsePattern.Expand() to expand the submenu;
//   - the last segment: after finding the element, try InvokePattern.Invoke(), and Expand() if it can be expanded.
//
// The script outputs "OK: <path>" to indicate success, otherwise outputs "ERROR: <reason>".
func buildWindowsUIMenuScript(windowID, title, path string) (string, error) {
	if windowID == "" && title == "" {
		return "", fmt.Errorf("at least one of the parameters window_id and title must be provided")
	}
	segments, err := parseWindowsUIMenuPath(path)
	if err != nil {
		return "", err
	}

	var rootExpr string
	if windowID != "" {
		rootExpr = "[System.Windows.Automation.AutomationElement]::FromHandle([IntPtr]" + windowID + ")"
	} else {
		quotedTitle := encodePowerShellText(title)
		rootExpr = "$w = Get-Process | Where-Object { $_.MainWindowTitle -like ('*' + " + quotedTitle + " + '*') } | Select-Object -First 1; " +
			"if ($w -eq $null) { Write-Output 'ERROR:no-window'; exit }; " +
			"[System.Windows.Automation.AutomationElement]::FromHandle([IntPtr]$w.MainWindowHandle)"
	}

	// Construct the PowerShell statements for level-by-level searching.
	var steps strings.Builder
	steps.WriteString("$cur = " + rootExpr + "; ")
	steps.WriteString("if ($cur -eq $null) { Write-Output 'ERROR:no-window'; exit }; ")
	for i, seg := range segments {
		quoted := encodePowerShellText(seg)
		steps.WriteString("$cond = New-Object System.Windows.Automation.PropertyCondition(" +
			"[System.Windows.Automation.AutomationElement]::NameProperty, " + quoted + "); ")
		steps.WriteString("$el = $cur.FindFirst([System.Windows.Automation.TreeScope]::Children, $cond); ")
		steps.WriteString("if ($el -eq $null) { $el = $cur.FindFirst([System.Windows.Automation.TreeScope]::Descendants, $cond) }; ")
		steps.WriteString("if ($el -eq $null) { Write-Output ('ERROR:not-found: " + quoted + "'); exit }; ")
		if i == len(segments)-1 {
			// The last segment: try Invoke, otherwise Expand.
			steps.WriteString("try { $p = $el.GetCurrentPattern([System.Windows.Automation.InvokePattern]::Pattern); " +
				"$p.Invoke(); Write-Output ('OK: " + quoted + "') } catch { " +
				"try { $e = $el.GetCurrentPattern([System.Windows.Automation.ExpandCollapsePattern]::Pattern); " +
				"$e.Expand(); Write-Output ('OK(expanded): " + quoted + "') } catch { " +
				"Write-Output ('ERROR:no-pattern: " + quoted + "') } }")
		} else {
			// Intermediate segment: expand the submenu.
			steps.WriteString("try { $e = $el.GetCurrentPattern([System.Windows.Automation.ExpandCollapsePattern]::Pattern); $e.Expand() } catch { }; ")
			steps.WriteString("$cur = $el; ")
		}
	}

	return windowsUIAddTypePreamble + "; " + steps.String(), nil
}

// buildWindowsControlFindPrefix constructs a PowerShell prefix for "locate window + locate control".
//
// After the returned script fragment runs, the variable $el points to the target control; if location fails, it outputs ERROR: and exits.
// Reused by windows.control.click / windows.control.set-text.
//
// At least one of windowID and title is provided to locate the window (same as tree/menu); at least one of name and automation_id
// is provided to locate the control within the window (by the Name or AutomationId property, with the Descendants scope).
// All user input (title/name/automation_id) is escaped by encodePowerShellText.
func buildWindowsControlFindPrefix(windowID, title, name, automationID string) (string, error) {
	if windowID == "" && title == "" {
		return "", fmt.Errorf("at least one of the parameters window_id and title must be provided")
	}
	if name == "" && automationID == "" {
		return "", fmt.Errorf("at least one of the parameters name and automation_id must be provided")
	}

	var rootExpr string
	if windowID != "" {
		rootExpr = "[System.Windows.Automation.AutomationElement]::FromHandle([IntPtr]" + windowID + ")"
	} else {
		quotedTitle := encodePowerShellText(title)
		rootExpr = "$w = Get-Process | Where-Object { $_.MainWindowTitle -like ('*' + " + quotedTitle + " + '*') } | Select-Object -First 1; " +
			"if ($w -eq $null) { Write-Output 'ERROR:no-window'; exit }; " +
			"[System.Windows.Automation.AutomationElement]::FromHandle([IntPtr]$w.MainWindowHandle)"
	}

	var find string
	if name != "" {
		quotedName := encodePowerShellText(name)
		find = "$cond = New-Object System.Windows.Automation.PropertyCondition(" +
			"[System.Windows.Automation.AutomationElement]::NameProperty, " + quotedName + "); " +
			"$el = $root.FindFirst([System.Windows.Automation.TreeScope]::Descendants, $cond); " +
			"if ($el -eq $null) { Write-Output ('ERROR:not-found-name: " + quotedName + "'); exit }"
	} else {
		quotedID := encodePowerShellText(automationID)
		find = "$cond = New-Object System.Windows.Automation.PropertyCondition(" +
			"[System.Windows.Automation.AutomationElement]::AutomationIdProperty, " + quotedID + "); " +
			"$el = $root.FindFirst([System.Windows.Automation.TreeScope]::Descendants, $cond); " +
			"if ($el -eq $null) { Write-Output ('ERROR:not-found-id: " + quotedID + "'); exit }"
	}

	return windowsUIAddTypePreamble + "; " +
		"$root = " + rootExpr + "; " +
		"if ($root -eq $null) { Write-Output 'ERROR:no-window'; exit }; " +
		find, nil
}

// buildWindowsControlClickScript constructs the PowerShell script for windows.control.click.
//
// After locating the control, trigger the click: prefer InvokePattern.Invoke() (buttons/links, etc.),
// otherwise SelectionItemPattern.Select() (list items/tabs, etc.).
// On success outputs "OK:invoked" / "OK:selected", on failure outputs "ERROR:...".
func buildWindowsControlClickScript(windowID, title, name, automationID string) (string, error) {
	prefix, err := buildWindowsControlFindPrefix(windowID, title, name, automationID)
	if err != nil {
		return "", err
	}
	action := "try { $p = $el.GetCurrentPattern([System.Windows.Automation.InvokePattern]::Pattern); " +
		"$p.Invoke(); Write-Output 'OK:invoked' } catch { " +
		"try { $s = $el.GetCurrentPattern([System.Windows.Automation.SelectionItemPattern]::Pattern); " +
		"$s.Select(); Write-Output 'OK:selected' } catch { " +
		"Write-Output 'ERROR:no-pattern' } }"
	return prefix + "; " + action, nil
}

// buildWindowsControlSetTextScript constructs the PowerShell script for windows.control.set-text.
//
// After locating the control, use ValuePattern.SetValue() to set the text (text boxes/edit boxes, etc.).
// text is escaped by encodePowerShellText into a single-quoted literal.
// On success outputs "OK:value-set", on failure outputs "ERROR:...".
func buildWindowsControlSetTextScript(windowID, title, name, automationID, text string) (string, error) {
	prefix, err := buildWindowsControlFindPrefix(windowID, title, name, automationID)
	if err != nil {
		return "", err
	}
	quotedText := encodePowerShellText(text)
	action := "try { $v = $el.GetCurrentPattern([System.Windows.Automation.ValuePattern]::Pattern); " +
		"$v.SetValue(" + quotedText + "); Write-Output 'OK:value-set' } catch { " +
		"Write-Output ('ERROR:no-value-pattern: ' + $_.Exception.Message) }"
	return prefix + "; " + action, nil
}
