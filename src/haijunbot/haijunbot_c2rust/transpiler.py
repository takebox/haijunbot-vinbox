class Transpiler:
    def __init__(
        self,
        project_root: Union[str, Path] = ".",
        crate_dir: Optional[Union[str, Path]] = None,
        plan_max_retries: int = DEFAULT_PLAN_MAX_RETRIES,  # Maximum retries for the planning stage (0 means unlimited retries)
        max_retries: int = 0,  # Compatible with the old interface; if not set, check_max_retries and test_max_retries are used
        check_max_retries: Optional[
            int
        ] = None,  # Maximum retries for the cargo check stage (0 means unlimited retries)
        test_max_retries: Optional[
            int
        ] = None,  # Maximum retries for the cargo test stage (0 means unlimited retries)
        review_max_iterations: int = DEFAULT_REVIEW_MAX_ITERATIONS,  # Maximum iterations for the review stage (0 means unlimited retries)
        disabled_libraries: Optional[
            List[str]
        ] = None,  # Disabled library list (these libraries are forbidden during implementation)
        root_symbols: Optional[
            List[str]
        ] = None,  # Root symbol list (the interfaces corresponding to these symbols must be exposed externally during implementation, except main)
        non_interactive: bool = True,
        enable_ffi_export_validation: bool = False,  # Enable FFI export validation
        quick_mode: bool = False,
    ) -> None:
        self.project_root = Path(project_root).resolve()
        self.data_dir = self.project_root / C2RUST_DIRNAME
        self.progress_path = self.data_dir / PROGRESS_JSON
        self.config_path = self.data_dir / CONFIG_JSON
        # JSONL path
        self.symbol_map_path = self.data_dir / SYMBOL_MAP_JSONL

        self.plan_max_retries = plan_max_retries
        # Compatible with the old interface: if only max_retries is set, it is also used for check and test
        if max_retries > 0 and check_max_retries is None and test_max_retries is None:
            self.check_max_retries = max_retries
            self.test_max_retries = max_retries
        else:
            self.check_max_retries = (
                check_max_retries
                if check_max_retries is not None
                else DEFAULT_CHECK_MAX_RETRIES
            )
            self.test_max_retries = (
                test_max_retries
                if test_max_retries is not None
                else DEFAULT_TEST_MAX_RETRIES
            )
        self.max_retries = max(
            self.check_max_retries, self.test_max_retries
        )  # Keep compatibility
        self.review_max_iterations = review_max_iterations
        self.non_interactive = non_interactive
        self.enable_ffi_export_validation = enable_ffi_export_validation
        self.quick_mode = quick_mode

        self.crate_dir = (
            Path(crate_dir) if crate_dir else default_crate_dir(self.project_root)
        )
        # Use a self-contained order.jsonl to record the built index, avoiding dependence on symbols.jsonl
        self.fn_index_by_id: Dict[int, FnRecord] = {}
        self.fn_name_to_id: Dict[str, int] = {}

        # The checkpoint/resume feature is always enabled by default
        self.resume = True

        # Initialize state variables (must be done before initializing the managers)
        # The commit id at the start of the current function (used for rollback on failure)
        self._current_function_start_commit: Optional[str] = None
        # The number of consecutive fix failures (used to decide whether a rollback is needed)
        self._consecutive_fix_failures: int = 0
        # The commit id before the tool call for each Agent (used for fine-grained detection)
        self._agent_before_commits: Dict[str, Optional[str]] = {}

        # Initialize the various functional modules
        self.config_manager = ConfigManager(self.data_dir, self.progress_path)
        self.progress = self.config_manager.progress

        # Load the configuration from a separate config file (supports backward-compatible migration from progress.json)
        config = self.config_manager.load_config()

        # If new root symbols or disabled libraries are provided, update the configuration; otherwise restore from the config file
        # Prefer the passed-in arguments; if None, restore from the config file
        if root_symbols is not None:
            # The passed-in argument is not None; use the passed-in value and save it
            self.root_symbols = root_symbols
        else:
            # The passed-in argument is None; restore from the config file
            # Use the configuration from the config file if present, otherwise use an empty list
            self.root_symbols = config.get("root_symbols", [])

        if disabled_libraries is not None:
            # The passed-in argument is not None; use the passed-in value and save it
            self.disabled_libraries = disabled_libraries
        else:
            # The passed-in argument is None; restore from the config file
            # Use the configuration from the config file if present, otherwise use an empty list
            self.disabled_libraries = config.get("disabled_libraries", [])

        # Read additional notes from the config file (cannot be passed via arguments; can only be set through the config file)
        self.additional_notes = config.get("additional_notes", "")

        # Save the configuration to a separate config file
        self.config_manager.save_config(
            self.root_symbols, self.disabled_libraries, self.additional_notes
        )

        # Initialize the other modules
        self.compile_commands_manager = CompileCommandsManager(self.project_root)
        self.git_manager = GitManager(str(self.crate_dir))
        self.module_manager = ModuleManager(self.crate_dir)

        # Initialize the Agent manager
        self.agent_manager = AgentManager(
            self.crate_dir,
            self.project_root,
            self.non_interactive,
            self.fn_index_by_id,
            self._get_crate_commit_hash,
            self._agent_before_commits,
            quick_mode=self.quick_mode,
        )
        self.agent_manager.set_reset_to_commit_func(self._reset_to_commit)

        # Initialize the planning manager (must be after AgentManager, because it needs to access agent_manager's methods)
        self.planning_manager = PlanningManager(
            self.project_root,
            self.crate_dir,
            self.data_dir,
            self.plan_max_retries,
            self.non_interactive,
            self.disabled_libraries,
            self.root_symbols,
            self._extract_compile_flags_for_planning,
            self._collect_callees_context,
            self._append_notes_for_planning,
            self._is_root_symbol_for_planning,
            self._get_crate_commit_hash,
            self.agent_manager.on_before_tool_call,
            self.agent_manager.on_after_tool_call,
            self._agent_before_commits,
            self.enable_ffi_export_validation,
        )

        # Initialize the code generation manager
        self.generation_manager = GenerationManager(
            self.project_root,
            self.crate_dir,
            self.data_dir,
            self.disabled_libraries,
            self._extract_compile_flags_for_generation,
            self._append_additional_notes,
            self._is_root_symbol,
            self._get_generation_agent,
            self._compose_prompt_with_context,
            self._check_and_handle_test_deletion,
            self._get_crate_commit_hash,
            self._ensure_top_level_pub_mod,
            self.enable_ffi_export_validation,
        )

        # The build manager will be lazily initialized when needed (because it needs to access other managers' methods)
        self.build_manager: Optional[Any] = None
        self._build_loop_has_fixes = False  # Flag whether fixes were made in the build loop

        # Initialize the review manager (must be after the other managers, because it needs to access their methods)
        from haijunbot.haijunbot_c2rust.transpiler_review import ReviewManager

        self.review_manager = ReviewManager(
            self.crate_dir,
            self.data_dir,
            self.non_interactive,
            self.review_max_iterations,
            self.disabled_libraries,
            self.progress,
            self._save_progress,
            self._read_source_span,
            self._collect_callees_context,
            self.compile_commands_manager.extract_compile_flags,
            self._is_root_symbol_for_review,
            self._get_crate_commit_hash,
            lambda: self._current_function_start_commit,
            self._compose_for_review,
            self._get_fix_agent,
            self._check_and_handle_test_deletion,
            self._append_notes_for_review,
            self._cargo_build_loop,
            self._get_build_loop_has_fixes,
            self._on_before_tool_call,
            self._on_after_tool_call,
            self._agent_before_commits,
            self._get_git_diff,
        )

        # Print a log after initialization is complete
        from haijunbot.haijunbot_utils.output import PrettyOutput

        PrettyOutput.auto_print(
            f"📋 [c2rust-transpiler][init] Initialization parameters: project_root={self.project_root} crate_dir={self.crate_dir} llm_group={get_llm_group()} plan_max_retries={self.plan_max_retries} check_max_retries={self.check_max_retries} test_max_retries={self.test_max_retries} review_max_iterations={self.review_max_iterations} disabled_libraries={self.disabled_libraries} root_symbols={self.root_symbols} non_interactive={self.non_interactive} enable_ffi_export_validation={self.enable_ffi_export_validation}"
        )
        # Symbol mapping stored using JSONL
        self.symbol_map = _SymbolMapJsonl(self.symbol_map_path)

        # Initialize the context collector and symbol mapper
        self.context_collector = ContextCollector(
            self.project_root,
            self.fn_index_by_id,
            self.fn_name_to_id,
            self.symbol_map,
        )
        self.symbol_mapper = SymbolMapper(
            self.symbol_map,
            self.progress,
            self.config_manager,
            self.git_manager,
        )

    def _extract_compile_flags_for_context(self, c_file_path: str) -> Dict[str, Any]:
        """Extract compile flags function adapted for AgentManager"""
        flags = self.compile_commands_manager.extract_compile_flags(c_file_path)
        return {"compile_flags": flags or []}

    def _extract_compile_flags_for_generation(self, c_file_path: str) -> List[str]:
        """Extract compile flags function adapted for GenerationManager"""
        flags = self.compile_commands_manager.extract_compile_flags(c_file_path)
        result: List[str] = []

        if flags is None:
            return result

        # extract_compile_flags returns a string, which needs parsing
        # Simplified here to return a list of strings
        if flags:
            result = [flags]

        return result

    def _collect_callees_context_for_context(self, rec: FnRecord) -> str:
        """Collect callee function context function adapted for AgentManager"""
        context_list = self._collect_callees_context(rec)
        return str(context_list)

    def _save_progress(self) -> None:
        """Save progress using atomic writes"""
        self.config_manager.save_progress()

    def _load_config(self) -> Dict[str, Any]:
        """Load the configuration from a separate config file (delegated to ConfigManager)"""
        return self.config_manager.load_config()

    def _save_config(self) -> None:
        """Save the configuration to a separate config file (delegated to ConfigManager)"""
        self.config_manager.save_config(
            self.root_symbols, self.disabled_libraries, self.additional_notes
        )

    def _read_source_span(self, rec: FnRecord) -> str:
        """Read a source snippet by start and end lines (ignoring column boundaries, as complete as possible)"""
        return self.context_collector.read_source_span(rec)

    def _load_order_index(self, order_jsonl: Path) -> None:
        """Load all records from the self-contained order.jsonl (delegated to ConfigManager)"""
        self.config_manager.load_order_index(
            order_jsonl, self.fn_index_by_id, self.fn_name_to_id
        )

    def _should_skip(self, rec: FnRecord) -> bool:
        """Determine whether the function should be skipped (delegated to SymbolMapper)"""
        return self.symbol_mapper.should_skip(rec)

    def _collect_callees_context(self, rec: FnRecord) -> List[Dict[str, Any]]:
        """Generate the referenced-symbol context list (delegated to ContextCollector)"""
        return self.context_collector.collect_callees_context(rec)

    def _untranslated_callee_symbols(self, rec: FnRecord) -> List[str]:
        """Return the callee function symbols not yet converted (delegated to ContextCollector)"""
        return self.context_collector.untranslated_callee_symbols(rec)

    def _append_additional_notes(self, prompt: str, _unused: str = "") -> str:
        """Append additional notes to the end of the hint (delegated to ContextCollector)"""
        return self.context_collector.append_additional_notes(
            prompt, self.additional_notes
        )

    def _build_module_selection_prompts(
        self,
        rec: FnRecord,
        c_code: str,
        callees_ctx: List[Dict[str, Any]],
        crate_tree: str,
    ) -> Tuple[str, str, str]:
        """Build the module selection hint (delegated to PlanningManager)"""
        return self.planning_manager.build_module_selection_prompts(
            rec, c_code, callees_ctx, crate_tree
        )

    def _plan_module_and_signature(
        self, rec: FnRecord, c_code: str
    ) -> Tuple[str, str, bool]:
        """Call the Agent to select the module and signature (delegated to PlanningManager)"""
        return self.planning_manager.plan_module_and_signature(rec, c_code)

    def _update_progress_current(
        self, rec: FnRecord, module: str, rust_sig: str
    ) -> None:
        """Update the current progress (delegated to AgentManager)"""
        self.agent_manager.update_progress_current(
            rec, module, rust_sig, self.progress, self._save_progress
        )

    # ========= Agent reuse and context concatenation helpers =========

    def _compose_prompt_with_context(self, prompt: str, for_fix: bool = False) -> str:
        """When reusing an Agent, prepend the previously built function context header to the current hint (delegated to AgentManager)"""
        return self.agent_manager.compose_prompt_with_context(prompt, for_fix)

    def _reset_function_context(
        self, rec: FnRecord, module: str, rust_sig: str, c_code: str
    ) -> None:
        """Initialize the current function's context and the reused-Agent cache (delegated to AgentManager)"""
        # Set the current function ID so that AgentManager can access it
        self.agent_manager._current_function_id = rec.id
        self.agent_manager.reset_function_context(
            rec,
            module,
            rust_sig,
            c_code,
            self._collect_callees_context_for_context,
            self._extract_compile_flags_for_context,
        )

    def _on_before_tool_call(
        self, agent: Any, current_response: Any = None, **kwargs: Any
    ) -> None:
        """Event handler before a tool call (delegated to AgentManager)"""
        return self.agent_manager.on_before_tool_call(agent, current_response, **kwargs)

    def _on_after_tool_call(
        self,
        agent: Any,
        current_response: Any = None,
        need_return: Any = None,
        tool_prompt: Any = None,
        **kwargs: Any,
    ) -> None:
        """Event handler after a tool call (delegated to AgentManager)"""
        return self.agent_manager.on_after_tool_call(
            agent, current_response, need_return, tool_prompt, **kwargs
        )

    def _get_code_agent(self) -> CodeAgentType:
        """Get the code generation/fix Agent (delegated to AgentManager, kept backward compatible)"""
        return self.agent_manager.get_code_agent()

    def _get_generation_agent(self) -> CodeAgentType:
        """Get the code generation Agent (delegated to AgentManager)"""
        return self.agent_manager.get_generation_agent()

    def _get_fix_agent(self, c_code: Optional[str] = None) -> CodeAgentType:
        """Get the fix Agent (delegated to AgentManager, recreated each time)"""
        return self.agent_manager.get_fix_agent(c_code)

    def _refresh_compact_context(
        self, rec: FnRecord, module: str, rust_sig: str
    ) -> None:
        """Refresh the compact context header (delegated to AgentManager)"""
        self.agent_manager.refresh_compact_context(rec, module, rust_sig)

    # ========= Code generation and fix =========

    def _is_root_symbol(self, symbol_name: str) -> bool:
        """Determine whether the function is a root symbol (excluding main)"""
        if not self.root_symbols:
            return False
        return symbol_name in self.root_symbols

    def _is_root_symbol_for_planning(self, rec: FnRecord) -> bool:
        """Root symbol check adapted for PlanningManager"""
        if not self.root_symbols:
            return False
        return (rec.name in self.root_symbols) or (rec.qname in self.root_symbols)

    def _is_root_symbol_for_review(self, rec: FnRecord) -> bool:
        """Root symbol check adapted for ReviewManager"""
        if not self.root_symbols:
            return False
        return (rec.name in self.root_symbols) or (rec.qname in self.root_symbols)

    def _extract_compile_flags_for_planning(self, c_file_path: str) -> Dict[str, Any]:
        """Extract compile flags function adapted for PlanningManager"""
        flags = self.compile_commands_manager.extract_compile_flags(c_file_path)
        return {"compile_flags": flags or []}

    def _append_notes_for_planning(self, prompt: str) -> str:
        """Additional notes function adapted for PlanningManager"""
        return self._append_additional_notes(prompt, "")

    def _append_notes_for_review(self, prompt: str) -> str:
        """Additional notes function adapted for ReviewManager"""
        return self._append_additional_notes(prompt, "")

    def _compose_for_review(self, prompt: str, for_fix: bool = True) -> str:
        """Hint concatenation function adapted for ReviewManager"""
        return self._compose_prompt_with_context(prompt, for_fix)

    def _build_generate_impl_prompt(
        self,
        rec: FnRecord,
        c_code: str,
        module: str,
        rust_sig: str,
        unresolved: List[str],
    ) -> str:
        """Build the code generation hint (delegated to GenerationManager)"""
        return self.generation_manager.build_generate_impl_prompt(
            rec, c_code, module, rust_sig, unresolved
        )

    def _code_agent_generate_impl(
        self,
        rec: FnRecord,
        c_code: str,
        module: str,
        rust_sig: str,
        unresolved: List[str],
    ) -> None:
        """Use a CodeAgent to generate/update the function implementation in the target module (delegated to GenerationManager)"""
        return self.generation_manager.code_agent_generate_impl(
            rec, c_code, module, rust_sig, unresolved
        )

    def _extract_rust_fn_name_from_sig(self, rust_sig: str) -> str:
        """Extract the function name from a rust signature (delegated to GenerationManager)"""
        return self.generation_manager.extract_rust_fn_name_from_sig(rust_sig)

    def _ensure_top_level_pub_mod(self, mod_name: str) -> None:
        """Ensure `pub mod <mod_name>;` exists in src/lib.rs (delegated to ModuleManager)"""
        self.module_manager.ensure_top_level_pub_mod(mod_name)

    def _ensure_mod_rs_decl(self, dir_path: Path, child_mod: str) -> None:
        """Ensure `pub mod <child_mod>;` exists in dir_path/mod.rs (delegated to ModuleManager)"""
        self.module_manager.ensure_mod_rs_decl(dir_path, child_mod)

    def _ensure_mod_chain_for_module(self, module: str) -> None:
        """Based on the target module file, complete the mod.rs declaration chain upward from the file's directory (delegated to ModuleManager)"""
        self.module_manager.ensure_mod_chain_for_module(module)

    def _module_file_to_crate_path(self, module: str) -> str:
        """Convert the module file path to a crate path prefix (delegated to ModuleManager)"""
        return self.module_manager.module_file_to_crate_path(module)

    def _ensure_cargo_toml_bin(
        self, bin_path: str, bin_name: Optional[str] = None
    ) -> None:
        """Ensure the [[bin]] configuration exists in Cargo.toml (delegated to ModuleManager)"""
        self.module_manager.ensure_cargo_toml_bin(bin_path, bin_name)

    def _resolve_pending_todos_for_symbol(
        self, symbol: str, callee_module: str, callee_rust_fn: str, callee_rust_sig: str
    ) -> None:
        """Resolve pending todo placeholders (delegated to SymbolMapper)"""
        # Use the fix Agent (pass None, since this method does not need the C code)
        self.symbol_mapper.resolve_pending_todos_for_symbol(
            symbol,
            callee_module,
            callee_rust_fn,
            callee_rust_sig,
            self.crate_dir,
            lambda: self._get_fix_agent(None),
            self._compose_for_review,
            self._check_and_handle_test_deletion,
        )

    def _init_build_manager(self) -> None:
        """Initialize the build manager"""
        if self.build_manager is None:
            from haijunbot.haijunbot_c2rust.transpiler_build import BuildManager  # type: ignore[attr-defined]

            self.build_manager = BuildManager(
                self.crate_dir,
                self.project_root,
                self.data_dir,
                self.test_max_retries,
                self.disabled_libraries,
                self.root_symbols,
                self.progress,
                self._save_progress,
                self._extract_compile_flags_for_generation,
                self._get_current_function_context_for_build,
                self._get_fix_agent,
                self._compose_prompt_with_context,
                self._check_and_handle_test_deletion,
                self._get_crate_commit_hash,
                self._reset_to_commit_for_build,
                self._append_additional_notes,
                lambda: self._consecutive_fix_failures,
                lambda v: setattr(self, "_consecutive_fix_failures", v),
                lambda: self._current_function_start_commit,
                self._get_git_diff,
                self.enable_ffi_export_validation,
            )

    def _classify_rust_error(self, text: str) -> List[str]:
        """Simple error classification (delegated to BuildManager)"""
        if self.build_manager is None:
            self._init_build_manager()
        return (
            self.build_manager.classify_rust_error(text)
            if self.build_manager is not None
            else []
        )

    def _get_current_function_context(self) -> Tuple[Dict[str, Any], str, str, str]:
        """
        Get the current function context information.
        Returns: (curr, sym_name, src_loc, c_code)
        """
        try:
            curr = self.progress.get("current") or {}
        except Exception:
            curr = {}
        sym_name = str(curr.get("qualified_name") or curr.get("name") or "")
        src_loc = (
            f"{curr.get('file')}:{curr.get('start_line')}-{curr.get('end_line')}"
            if curr
            else ""
        )
        c_code = ""
        try:
            cf = curr.get("file")
            s = int(curr.get("start_line") or 0)
            e = int(curr.get("end_line") or 0)
            if cf and s:
                p = Path(cf)
                if not p.is_absolute():
                    p = (self.project_root / p).resolve()
                if p.exists():
                    lines = p.read_text(encoding="utf-8", errors="replace").splitlines()
                    s0 = max(1, s)
                    e0 = min(len(lines), max(e, s0))
                    c_code = "\n".join(lines[s0 - 1 : e0])
        except Exception:
            c_code = ""
        return curr, sym_name, src_loc, c_code

