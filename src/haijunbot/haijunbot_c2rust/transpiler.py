# -*- coding: utf-8 -*-
"""
C2Rust transpiler module

Goals:
- Transpile function by function following the translation_order.jsonl order generated by the scanner
- For each function:
  1) Prepare the context: C source snippet + location information, callee symbols (if already transpiled, provide the Rust module and symbol; otherwise provide the original C location information), and the crate directory structure
  2) Create the "module selection and signature Agent": have it choose a suitable Rust module path and output the function signature in the summary
  3) Record the current progress to progress.json
  4) Based on the above information and the output location, create a CodeAgent to generate the transpiled Rust function
  5) Try cargo build; if it fails, create a CodeAgent with the error context to fix it until the build passes or the limit is reached
  6) Create a code review Agent; if the summary points out problems, have a CodeAgent optimize until the summary indicates there are no problems
  7) Mark the function as transpiled and record the C symbol -> Rust symbol/module mapping to symbol_map.jsonl (JSONL, one mapping per line, supporting duplicates and overloading)

Notes:
- This module provides run_transpile(...) as the public entry point, later mounted as a subcommand in eli.py
- Reuse the existing Agent/CodeAgent capabilities as much as possible to keep intrusiveness minimal and stability high
"""

