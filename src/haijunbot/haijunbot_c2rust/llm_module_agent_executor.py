"""Executor for the LLM module planning Agent."""

import os
import subprocess

from haijunbot.haijunbot_utils.config import get_llm_group
from haijunbot.haijunbot_utils.exception_utils import save_exception
from haijunbot.haijunbot_utils.output import PrettyOutput

# -*- coding: utf-8 -*-
from pathlib import Path
from typing import List
from typing import Optional
from typing import Union
from typing import cast

from haijunbot.haijunbot_c2rust.llm_module_agent_apply import (
    apply_project_structure_from_json,
)
from haijunbot.haijunbot_c2rust.llm_module_agent_utils import parse_project_json_entries
from haijunbot.haijunbot_c2rust.llm_module_agent_utils import resolve_created_dir


def execute_llm_plan(
    out: Optional[Union[Path, str]] = None,
    apply: bool = False,
    crate_name: Optional[Union[Path, str]] = None,
    non_interactive: bool = True,
    enable_ffi_export_validation: bool = False,
) -> List:
    """
    Return the raw JSON text of the directory structure generated by the LLM (from the <PROJECT> block).
    Do not parse it, so it can later be applied as-is and processed with a more robust parser when needed.
    """
    # execute_llm_plan is the top-level entry point and needs to perform cleanup (skip_cleanup=False)
    # Import lazily to avoid circular dependency
    from haijunbot.haijunbot_c2rust.llm_module_agent import plan_crate_json_text

    json_text = plan_crate_json_text(skip_cleanup=False)
    entries, parse_error = parse_project_json_entries(json_text)
    if parse_error:
        raise ValueError(f"JSON parsing failed: {parse_error}")
    if not entries:
        raise ValueError("[c2rust-llm-planner] Failed to parse the directory structure from the LLM output. Aborting.")

    # 2) If it needs to be applied to disk
    if apply:
        target_root = crate_name if crate_name else "."
        try:
            apply_project_structure_from_json(json_text, project_root=target_root)
            PrettyOutput.auto_print("[c2rust-llm-planner] Project structure applied.")
        except Exception as e:
            PrettyOutput.auto_print(f"[c2rust-llm-planner] Failed to apply project structure: {e}")
            raise

        # Post-apply: check the generated directory structure and use a CodeAgent to update Cargo.toml
        from haijunbot.haijunbot_code_agent.code_agent import (
            CodeAgent,
        )  # Import lazily to avoid global coupling

        # Resolve the crate directory path (consistent with the apply logic)
        try:
            created_dir = resolve_created_dir(target_root)
        except Exception:
            # Fallback: if it cannot be resolved, use the passed-in target_root directly
            created_dir = Path(target_root)

        # Perform git initialization and initial commit inside the crate directory (per the new strategy)
        try:
            # Initialize the git repository (this command is idempotent if it already exists)
            subprocess.run(["git", "init"], check=False, cwd=str(created_dir))
            # Add all files and attempt to commit
            subprocess.run(["git", "add", "-A"], check=False, cwd=str(created_dir))
            subprocess.run(
                ["git", "commit", "-m", "[c2rust-llm-planner] init crate"],
                check=False,
                cwd=str(created_dir),
            )
        except Exception:
            # Stay robust; do not let a git failure affect the main flow
            pass

        # Build the directory context for the CodeAgent (a simplified tree)
        def _format_tree(root: Path) -> str:
            lines: List[str] = []
            exclude = {".git", "target", ".haijunbot"}
            if not root.exists():
                return ""
            for p in sorted(root.rglob("*")):
                if any(part in exclude for part in p.parts):
                    continue
                rel = p.relative_to(root)
                depth = len(rel.parts) - 1
                indent = "  " * depth
                name = rel.name + ("/" if p.is_dir() else "")
                lines.append(f"{indent}- {name}")
            return "\n".join(lines)

        dir_ctx = _format_tree(created_dir)
        crate_pkg_name = created_dir.name

        requirement_lines = [
            "Goal: ensure that `cargo build` succeeds in this crate directory; if it fails, make minimal modifications based on the error and retry until the build passes.",
            f"- crate_dir: {created_dir}",
            f"- crate_name: {crate_pkg_name}",
            "Directory structure (partial):",
            dir_ctx,
            "",
            "Execution and repair procedure (must be followed in order; multiple iterations are allowed):",
            "1) First complete the Rust module declarations (only minimally append/upgrade; do not overwrite business implementations):",
            "   - Scan the src directory:",
            "     * In each subdirectory (except the src root), create or update mod.rs, appending only the missing `pub mod <child>;` declarations;",
            "     * In src/lib.rs, append `pub mod <name>;` for top-level submodules; do not create src/mod.rs; ignore self-references in lib.rs and main.rs;",
            "   - If `mod <name>;` exists but is not pub, upgrade it in place to `pub mod <name>;`, preserving the original indentation and other content;",
            "   - It is strictly forbidden to delete existing declarations or modify non-declaration code;",
            '2) In the [package] section of Cargo.toml, set edition: "2024"; if the local toolchain does not support 2024, downgrade to "2021" and record the reason in the description; keep other existing fields and dependencies unchanged.',
            "3) Configure the entry points according to the actual state of the current source code:",
            "   - Library only: configure only [lib] (path=src/lib.rs); do not generate main.rs;"
            + (
                '**Important**: you must add `crate-type = ["cdylib", "rlib"]` (or at least include "cdylib") to the [lib] configuration to ensure the artifact includes cdylib. It may also include rlib, but it must not be rlib only.'
                if enable_ffi_export_validation
                else ""
            ),
            "   - Single executable: when src/main.rs exists, configure [[bin]] or the default binary; optionally keep [lib] to hold shared logic;"
            + (
                '**Important**: if [lib] is configured, you must add `crate-type = ["cdylib", "rlib"]` (or at least include "cdylib") to the [lib] configuration to ensure the artifact includes cdylib. It may also include rlib, but it must not be rlib only.'
                if enable_ffi_export_validation
                else ""
            ),
            "   - Multiple executables: configure [[bin]] for each src/bin/<name>.rs; put shared code in src/lib.rs;"
            + (
                '**Important**: you must add `crate-type = ["cdylib", "rlib"]` (or at least include "cdylib") to the [lib] configuration to ensure the artifact includes cdylib. It may also include rlib, but it must not be rlib only.'
                if enable_ffi_export_validation
                else ""
            ),
            "   - Do not create placeholder entry points inconsistent with the directory structure.",
            "4) For source files used as entry points: if fn main() does not exist, add only a minimal working implementation (do not change existing implementations):",
            '   fn main() { println!("ok"); }',
            "5) Run a build verification: `cargo build -q` (or `cargo check -q`).",
            "6) If the build fails, read the errors, make minimal fixes, then build again; repeat until it succeeds. Only the following fix types are allowed:",
            "   - Missing dependencies: add necessary dependencies with stable versions to [dependencies] (prefer no features), avoiding new unused dependencies;",
            "   - Entry/crate-type configuration errors: fix the name/path/crate-type of [lib] or [[bin]] to match the directory and entry files;",
            "   - Language/toolchain incompatibility: adjust edition from 2024 to 2021; add a rust-version requirement if necessary;",
            "   - Syntax-level/minimal implementation missing: in the entry files only, add the necessary use/empty implementation/feature gate to pass compilation, avoiding changes to non-entry business files;",
            "   - Do not delete or move existing files and directories.",
            "7) After each round of modification, you must run `cargo build -q` to verify, until the build succeeds.",
            "",
            "Modification constraints:",
            "- Allowed file scope for modification: Cargo.toml, src/lib.rs, src/main.rs, src/bin/*.rs, src/**/mod.rs (minimal necessary changes only); do not modify other files unless it is to fix the build or complete module declarations.",
            "- Keep existing content and structure unchanged as much as possible; do not introduce build-unrelated changes or formatting.",
            "",
            "Delivery requirements:",
            "- Submit the actually modified files as a patch;",
            "- In the final reply, briefly describe the changes made and the final `cargo build` result (success/failure and reason).",
        ]
        requirement_text = "\n".join(requirement_lines)

        prev_cwd = os.getcwd()
        try:
            # Switch to the crate directory to run the CodeAgent and build
            os.chdir(str(created_dir))
            PrettyOutput.auto_print(
                f"[c2rust-llm-planner] Switched to crate directory: {os.getcwd()}; initializing CodeAgent"
            )
            PrettyOutput.auto_print(
                f"[c2rust-llm-planner] Using model group: {get_llm_group()}"
            )
            try:
                # Verify whether the model configuration is still valid after switching directories
                # CodeAgent uses the smart model, so use the smart configuration here too to display the correct model information
                from haijunbot.haijunbot_utils.config import get_smart_model_name
                from haijunbot.haijunbot_utils.config import get_smart_platform_name

                resolved_model = get_smart_model_name()
                resolved_platform = get_smart_platform_name()
                PrettyOutput.auto_print(
                    f"[c2rust-llm-planner] Resolved model configuration: platform={resolved_platform}, model={resolved_model}"
                )
            except Exception as e:
                PrettyOutput.auto_print(
                    f"[c2rust-llm-planner] Warning: unable to verify model configuration: {e}"
                )

            try:
                agent = CodeAgent(
                    need_summary=False,
                    non_interactive=non_interactive,
                    enable_task_list_manager=False,
                    disable_review=True,
                    enable_auto_rule_select=False,
                    quick_mode=True,
                )
                # Verify the model configuration inside the agent
                if hasattr(agent, "model") and agent.model:
                    actual_model = getattr(agent.model, "model_name", "unknown")
                    actual_platform = type(agent.model).__name__
                    PrettyOutput.auto_print(
                        f"[c2rust-llm-planner] Model inside CodeAgent: {actual_platform}.{actual_model}"
                    )
                cast(CodeAgent, agent).run(
                    requirement_text, prefix="[c2rust-llm-planner]", suffix=""
                )
                PrettyOutput.auto_print(
                    "[c2rust-llm-planner] Initial CodeAgent run completed."
                )
            except Exception as e:
                error_msg = str(e)
                if "does not exist" in error_msg or "404" in error_msg:
                    PrettyOutput.auto_print(
                        f"[c2rust-llm-planner] Model configuration error: {error_msg}"
                    )
                    PrettyOutput.auto_print(
                        f"[c2rust-llm-planner] Hint: please check whether the configuration of model group '{get_llm_group()}' is correct"
                    )
                    PrettyOutput.auto_print(
                        f"[c2rust-llm-planner] Current working directory: {os.getcwd()}"
                    )
                    # Try to display the currently resolved model configuration (CodeAgent uses the smart model)
                    try:
                        from haijunbot.haijunbot_utils.config import get_smart_model_name
                        from haijunbot.haijunbot_utils.config import get_smart_platform_name

                        PrettyOutput.auto_print(
                            f"[c2rust-llm-planner] Currently resolved model: {get_smart_platform_name()}/{get_smart_model_name()}"
                        )
                    except Exception as e:
                        save_exception(
                            e,
                            module="haijunbot_c2rust.llm_module_agent_executor",
                            function="_format_tree",
                        )
                        pass
                raise

            # Enter the build-and-fix loop: if the build fails, create a new CodeAgent carrying the error context to perform minimal fixes
            iter_count = 0
            while True:
                iter_count += 1
                PrettyOutput.auto_print(
                    f"[c2rust-llm-planner] Executing in {os.getcwd()}: cargo build -q"
                )
                build_res = subprocess.run(
                    ["cargo", "build", "-q"],
                    capture_output=True,
                    text=True,
                    check=False,
                )
                stdout = build_res.stdout or ""
                stderr = build_res.stderr or ""
                output = (stdout + "\n" + stderr).strip()

                if build_res.returncode == 0:
                    PrettyOutput.auto_print("[c2rust-llm-planner] Cargo build succeeded.")
                    break

                PrettyOutput.auto_print(
                    f"[c2rust-llm-planner] Cargo build failed (iter={iter_count})."
                )
                # Print the compilation error output for visualization and debugging
                PrettyOutput.auto_print("[c2rust-llm-planner] Build error output:")
                PrettyOutput.auto_print(output)
                # Use the error information as context, append repair principles, and create a new CodeAgent to perform minimal fixes
                repair_prompt = "\n".join(
                    [
                        requirement_text,
                        "",
                        "Please make minimal fixes based on the following build errors, then run `cargo build` again to verify:"
                        "<BUILD_ERROR>",
                        output,
                        "</BUILD_ERROR>",
                    ]
                )

                PrettyOutput.auto_print(
                    f"[c2rust-llm-planner][iter={iter_count}] Using model group: {get_llm_group()}"
                )
                try:
                    repair_agent = CodeAgent(
                        need_summary=False,
                        non_interactive=non_interactive,
                        enable_task_list_manager=False,
                        disable_review=True,
                        enable_auto_rule_select=False,
                        quick_mode=True,
                    )
                    cast(CodeAgent, repair_agent).run(
                        repair_prompt,
                        prefix=f"[c2rust-llm-planner][iter={iter_count}]",
                        suffix="",
                    )
                except Exception as e:
                    error_msg = str(e)
                    if "does not exist" in error_msg or "404" in error_msg:
                        PrettyOutput.auto_print(
                            f"[c2rust-llm-planner][iter={iter_count}] Model configuration error: {error_msg}"
                        )
                        PrettyOutput.auto_print(
                            f"[c2rust-llm-planner][iter={iter_count}] Hint: please check the configuration of model group '{get_llm_group()}'"
                        )
                    raise
                # Do not switch directories; stay in the original working directory
        finally:
            # Restore the previous working directory
            os.chdir(prev_cwd)

    # 3) Output the JSON to a file (if specified) and return the parsed entries
    if out is not None:
        out_path = Path(out)
        out_path.parent.mkdir(parents=True, exist_ok=True)
        # Write out the original text for readability
        out_path.write_text(json_text, encoding="utf-8")
        PrettyOutput.auto_print(f"[c2rust-llm-planner] JSON written to: {out_path}")

    return entries
