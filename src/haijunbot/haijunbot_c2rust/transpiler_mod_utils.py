def ensure_mod_chain_for_module(crate_dir: Path, module: str) -> None:
    """
    Based on the target module file, complete the mod.rs declaration chain upward from the directory containing that file:
    - For src/foo/bar.rs: ensure `pub mod bar;` in src/foo/mod.rs
      and instead of modifying the upper-level src/mod.rs, ensure `pub mod foo;` in src/lib.rs
    - For src/foo/bar/mod.rs: ensure `pub mod bar;` in src/foo/mod.rs
    - For multi-level directories, ensure `pub mod <child>;` for the subdirectory at each level in the upper mod.rs
    """
    try:
        mp = Path(module)
        base = mp
        if not mp.is_absolute():
            base = (crate_dir / module).resolve()
        crate_root = crate_dir.resolve()
        # Must be under crate/src
        rel = base.relative_to(crate_root)
        rel_s = str(rel).replace("\\", "/")
        if not rel_s.startswith("src/"):
            return
        # Compute the starting directory and the first child module name
        inside = rel_s[len("src/") :].strip("/")
        if not inside:
            return
        parts = [p for p in inside.split("/") if p]  # Filter out empty strings
        if parts[-1].endswith(".rs"):
            if parts[-1] in ("lib.rs", "main.rs"):
                return
            child = parts[-1][:-3]  # Strip .rs
            # Filter out the "mod" keyword
            if child == "mod":
                return
            if len(parts) > 1:
                start_dir = crate_root / "src" / "/".join(parts[:-1])
            else:
                start_dir = crate_root / "src"
            # Ensure start_dir is under crate/src
            try:
                start_dir_rel = start_dir.relative_to(crate_root)
                if not str(start_dir_rel).replace("\\", "/").startswith("src/"):
                    return
            except ValueError:
                return
            # Ensure pub mod <child> in the current directory's mod.rs
            if start_dir.name != "src":
                ensure_mod_rs_decl(start_dir, child)
            # Going upward level by level, ensure the parent directory declares pub mod for the current directory
            cur_dir = start_dir
        else:
            # The end is a directory (mod.rs case): ensure the parent directory pub mods that directory
            if parts:
                cur_dir = crate_root / "src" / "/".join(parts)
                # Ensure cur_dir is under crate/src
                try:
                    cur_dir_rel = cur_dir.relative_to(crate_root)
                    if not str(cur_dir_rel).replace("\\", "/").startswith("src/"):
                        return
                except ValueError:
                    return
            else:
                return
        # Go up level by level to the src root (do not modify src/mod.rs; the top level is exposed by lib.rs)
        while True:
            parent = cur_dir.parent
            if not parent.exists():
                break
            # Ensure we do not go above the crate root directory
            try:
                parent.relative_to(crate_root)
            except ValueError:
                # parent is not under crate_root; stop traversing upward
                break
            if parent.name == "src":
                # The top level is handled by ensure_top_level_pub_mod
                break
            # Ensure pub mod <cur_dir.name> in parent/mod.rs
            if cur_dir.name == "mod":
                cur_dir = parent
                continue
            try:
                parent_rel = parent.relative_to(crate_root)
                if str(parent_rel).replace("\\", "/").startswith("src/"):
                    ensure_mod_rs_decl(parent, cur_dir.name)
            except (ValueError, Exception):
                # parent is not under crate/src; skip
                break
            cur_dir = parent
    except Exception as e:
        save_exception(
            e,
            module="haijunbot_c2rust.transpiler_mod_utils",
            function="ensure_mod_chain_for_module",
        )
        pass


def module_file_to_crate_path(crate_dir: Path, module: str) -> str:
    """
    Convert a module file path to a crate path prefix:
    - src/lib.rs -> crate
    - src/foo/mod.rs -> crate::foo
    - src/foo/bar.rs -> crate::foo::bar
    Supports absolute paths: if module is an absolute path located under the crate root, it is automatically converted to a relative path before parsing;
    Otherwise (paths that cannot be resolved as under crate/src) uniformly return 'crate'
    """
    mod = str(module).strip()
    # If an absolute path under crate_dir is passed, convert it to a relative path for subsequent parsing by the src/ prefix
    try:
        mp = Path(mod)
        if mp.is_absolute():
            try:
                rel = mp.resolve().relative_to(crate_dir.resolve())
                mod = str(rel).replace("\\", "/")
            except Exception:
                # The absolute path is not under crate_dir; keep it as is
                pass
    except Exception as e:
        save_exception(
            e,
            module="haijunbot_c2rust.transpiler_mod_utils",
            function="module_file_to_crate_path",
        )
        pass
    # Normalize the ./ prefix
    if mod.startswith("./"):
        mod = mod[2:]
    # Only handle module files located under src/
    if not mod.startswith("src/"):
        return "crate"
    p = mod[len("src/") :]
    if p.endswith("mod.rs"):
        p = p[: -len("mod.rs")]
    elif p.endswith(".rs"):
        p = p[: -len(".rs")]
    p = p.strip("/")
    return "crate" if not p else "crate::" + p.replace("/", "::")
