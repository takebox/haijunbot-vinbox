# -*- coding: utf-8 -*-
"""
Library-based dependency replacer for C→Rust migration (LLM-only subtree evaluation).

Key points:
- Does not depend on pruner; only reuses the generic tool functions of the scanner
- Provide a summary of the "dependency subtree (the root function and its reachable function set)" and local source snippets to the LLM, which evaluates whether the entire subtree can be replaced by "one or more mature APIs of the specified standard library/third-party crate (composable, multi-library cooperative)"
- If replaceable: replace the root function's ref with that library API (as a placeholder of the form lib::<name>, supporting multi-library combination), and delete all of its descendant function nodes (types are unaffected)
- Supports disabled-library constraints: disabled_libraries (list[str]) may be passed; if the LLM suggestion hits a disabled library, it is forcibly judged as non-replaceable and a note is recorded
- Checkpoint/resume: resume can be enabled; use library_replacer_checkpoint.json to record eval_counter/processed/pruned/selected and other information, matching and resuming based on a key composed of the critical inputs; writes are atomic to prevent corruption
- Primary library field fallback strategy: when a libraries list exists, prefer the first as primary; otherwise fall back to the single library field; if both are empty, leave it empty
- Entry protection: skip main by default (multiple entry names can be configured via the environment variables c2rust_delay_entry_symbols/c2rust_delay_entries/C2RUST_DELAY_ENTRIES)

Input data:
- symbols.jsonl (or a passed-in .jsonl path): the unified symbol table generated by the scanner; see scanner.py for the fields
- Optional candidates (list of names or qualified names): evaluate only these symbols as roots, with the scope limited to their reachable subtree
- Optional disabled_libraries (list[str]): library names forbidden during evaluation (a hit is treated as non-replaceable)

Output:
- symbols_library_pruned.jsonl: the pruned symbol table (default name, customizable via a parameter)
- library_replacements.jsonl: the mapping from replacement roots to library information (JSONL, one per line: {id,name,qualified_name,library,libraries,function,apis?,confidence,notes?,mode})
- Compatibility outputs:
    - symbols_prune.jsonl: equivalent to the main output
    - symbols.jsonl: generic alias (for uniform reading by subsequent processes)
    - translation_order_prune.jsonl: the translation order of the pruning stage
    - translation_order.jsonl: generic alias (consistent with the pruning stage)
"""

from __future__ import annotations


from haijunbot.haijunbot_utils.exception_utils import save_exception
import json
import shutil
from pathlib import Path
from typing import Any
from typing import Dict
from typing import List
from typing import Optional
from typing import Set
from typing import Tuple

from haijunbot.haijunbot_utils.output import PrettyOutput
from haijunbot.haijunbot_c2rust.constants import DEFAULT_CHECKPOINT_FILE
from haijunbot.haijunbot_c2rust.constants import DEFAULT_CHECKPOINT_INTERVAL
from haijunbot.haijunbot_c2rust.constants import MAX_NOTES_DISPLAY_LENGTH
from haijunbot.haijunbot_c2rust.library_replacer_checkpoint import create_checkpoint_state
from haijunbot.haijunbot_c2rust.library_replacer_checkpoint import load_checkpoint_if_match
from haijunbot.haijunbot_c2rust.library_replacer_checkpoint import make_checkpoint_key
from haijunbot.haijunbot_c2rust.library_replacer_checkpoint import periodic_checkpoint_save
from haijunbot.haijunbot_c2rust.library_replacer_llm import check_llm_availability
from haijunbot.haijunbot_c2rust.library_replacer_llm import create_llm_model
from haijunbot.haijunbot_c2rust.library_replacer_llm import llm_evaluate_subtree
from haijunbot.haijunbot_c2rust.library_replacer_loader import build_evaluation_order
from haijunbot.haijunbot_c2rust.library_replacer_loader import build_function_graph
from haijunbot.haijunbot_c2rust.library_replacer_loader import collect_descendants
from haijunbot.haijunbot_c2rust.library_replacer_loader import load_symbols
from haijunbot.haijunbot_c2rust.library_replacer_loader import process_candidate_scope
from haijunbot.haijunbot_c2rust.library_replacer_output import write_output_symbols
from haijunbot.haijunbot_c2rust.library_replacer_utils import is_entry_function
from haijunbot.haijunbot_c2rust.library_replacer_utils import load_additional_notes
from haijunbot.haijunbot_c2rust.library_replacer_utils import normalize_disabled_libraries
from haijunbot.haijunbot_c2rust.library_replacer_utils import resolve_symbols_jsonl_path
from haijunbot.haijunbot_c2rust.library_replacer_utils import setup_output_paths
from haijunbot.haijunbot_c2rust.scanner import compute_translation_order_jsonl


def apply_library_replacement(
    db_path: Path,
    library_name: str,
    llm_group: Optional[str] = None,
    candidates: Optional[List[str]] = None,
    out_symbols_path: Optional[Path] = None,
    out_mapping_path: Optional[Path] = None,
    max_funcs: Optional[int] = None,
    disabled_libraries: Optional[List[str]] = None,
    resume: bool = True,
    checkpoint_path: Optional[Path] = None,
    checkpoint_interval: int = DEFAULT_CHECKPOINT_INTERVAL,
    clear_checkpoint_on_done: bool = True,
    non_interactive: bool = True,
) -> Dict[str, Path]:
    """
    Based on the dependency graph, the LLM decides and replaces/prunes function roots that satisfy "the entire subtree can be replaced by a single API of the specified library".

    Parameters:
        - db_path: the path to symbols.jsonl or the directory containing it
        - library_name: the specified library name (such as 'std', 'regex'); requires the LLM to select APIs only from that library
        - llm_group: optional; the model group used for evaluation
        - candidates: evaluate only these functions as roots (names or qualified names); by default evaluate all root functions (no incoming edges)
        - out_symbols_path/out_mapping_path: output file paths (use defaults if omitted)
        - max_funcs: the maximum number of roots for LLM evaluation (rate limiting/debugging)
        - disabled_libraries: the list of disabled open-source library names (not allowed in evaluation/suggestions; explicitly stated in the hint)
    Returns:
        Dict[str, Path]: {"symbols": new symbol table path, "mapping": replacement mapping path, "symbols_prune": compatibility symbol table path, "order": generic order path, "order_prune": pruning-stage order path}
    """
    sjsonl = resolve_symbols_jsonl_path(db_path)
    if not sjsonl.exists():
        raise FileNotFoundError(f"symbols.jsonl not found: {sjsonl}")

    data_dir = sjsonl.parent
    (
        out_symbols_path,
        out_mapping_path,
        out_symbols_prune_path,
        order_prune_path,
        alias_order_path,
    ) = setup_output_paths(data_dir, out_symbols_path, out_mapping_path)

    # Default checkpoint path
    if checkpoint_path is None:
        checkpoint_path = data_dir / DEFAULT_CHECKPOINT_FILE

    # Read symbols
    all_records, by_id, name_to_id, func_ids, id_refs_names = load_symbols(sjsonl)

    # Build function edges (id->id)
    adj_func = build_function_graph(func_ids, id_refs_names, name_to_id)

    # Build the evaluation order
    root_funcs = build_evaluation_order(sjsonl, func_ids, adj_func)

    # Reachability cache (must be defined before candidates are used to avoid forward references)
    desc_cache: Dict[int, Set[int]] = {}

    # If candidates are passed in, evaluate only these nodes (filtered by the order above) and limit the scope:
    # - Keep only the functions reachable from these roots; delete unreachable functions directly (type records are kept)
    root_funcs, scope_unreachable_funcs = process_candidate_scope(
        candidates, all_records, root_funcs, func_ids, adj_func, desc_cache
    )

    # LLM availability
    (
        model_available,
        PlatformRegistry,
        get_smart_platform_name,
        get_smart_model_name,
        get_llm_config,
    ) = check_llm_availability()

    # Preprocess disabled libraries
    disabled_norm, disabled_display = normalize_disabled_libraries(disabled_libraries)

    # Read additional notes
    additional_notes = load_additional_notes(data_dir)

    # Checkpoint/resume support: tool functions and key construction
    ckpt_path: Path = (
        Path(checkpoint_path)
        if checkpoint_path is not None
        else (data_dir / DEFAULT_CHECKPOINT_FILE)
    )
    checkpoint_key = make_checkpoint_key(
        sjsonl, library_name, llm_group, candidates, disabled_libraries, max_funcs
    )

    def new_model() -> Optional[Any]:
        return create_llm_model(
            llm_group,
            disabled_display,
            model_available,
            PlatformRegistry,
            get_smart_platform_name,
            get_smart_model_name,
            get_llm_config,
        )

    # Evaluation stage: if a node is evaluated as non-replaceable, continue evaluating its child nodes (recursive/depth-first)
    eval_counter = 0
    pruned_dynamic: Set[int] = set()  # Dynamically accumulated set of functions "to be pruned" (excluding selected roots)
    selected_roots: List[
        Tuple[int, Dict[str, Any]]
    ] = []  # Replaceable roots selected in real time (fid, LLM result)
    processed_roots: Set[int] = set()  # Set of roots already processed (evaluated or skipped)
    root_funcs_processed: Set[int] = set()  # Set of processed initial root functions (for progress display)
    last_ckpt_saved = 0  # The counter value at the last save

    # If a matching checkpoint file exists, load and resume it
    loaded_ckpt = load_checkpoint_if_match(ckpt_path, resume, checkpoint_key)
    if resume and loaded_ckpt:
        try:
            eval_counter = int(loaded_ckpt.get("eval_counter") or 0)
        except Exception as e:
            save_exception(
                e, module="haijunbot_c2rust.library_replacer", function="new_model"
            )
            pass
        try:
            processed_roots = set(
                int(x) for x in (loaded_ckpt.get("processed_roots") or [])
            )
        except Exception:
            processed_roots = set()
        try:
            pruned_dynamic = set(
                int(x) for x in (loaded_ckpt.get("pruned_dynamic") or [])
            )
        except Exception:
            pruned_dynamic = set()
        try:
            sr_list = []
            for it in loaded_ckpt.get("selected_roots") or []:
                if isinstance(it, dict) and "fid" in it and "res" in it:
                    try:
                        fid_val = int(it["fid"])
                        res_val = it["res"]
                        if isinstance(res_val, dict):
                            sr_list.append((fid_val, res_val))
                    except (ValueError, TypeError, KeyError):
                        continue
            selected_roots = sr_list
            if selected_roots:
                PrettyOutput.auto_print(
                    f"[c2rust-library] Restored selected_roots from checkpoint: {len(selected_roots)} replaceable roots"
                )
            else:
                PrettyOutput.auto_print(
                    "[c2rust-library] Warning: selected_roots is empty when restoring from checkpoint, which may cause library_replacements.jsonl to be empty"
                )
        except Exception as e:
            selected_roots = []
            PrettyOutput.auto_print(
                f"[c2rust-library] Error restoring selected_roots from checkpoint: {e}; an empty list will be used"
            )
        # Restore the set of processed initial root functions (filter root_funcs out of processed_roots)
        try:
            root_funcs_processed = {fid for fid in processed_roots if fid in root_funcs}
        except Exception:
            root_funcs_processed = set()
        PrettyOutput.auto_print(
            f"[c2rust-library] Restored from checkpoint: evaluated={eval_counter}, processed roots={len(processed_roots)}, pruned={len(pruned_dynamic)}, selected replaceable roots={len(selected_roots)}"
        )

    def evaluate_node(fid: int, is_root_func: bool = False) -> None:
        nonlocal eval_counter, last_ckpt_saved
        # Rate limiting
        if max_funcs is not None and eval_counter >= max_funcs:
            return
        # If this node has been marked as pruned or already processed, skip it
        if fid in pruned_dynamic or fid in processed_roots or fid not in func_ids:
            return

        # Build the subtree and print progress
        desc = collect_descendants(fid, adj_func, desc_cache)
        rec_meta = by_id.get(fid, {})
        label = rec_meta.get("qualified_name") or rec_meta.get("name") or f"sym_{fid}"
        # Compute progress: distinguish initial root functions from recursively evaluated child nodes
        total_roots = len(root_funcs)
        total_evaluated = len(processed_roots) + 1  # +1 because the current one is about to be processed
        if is_root_func:
            # Initial root function: show (current root function index/total root functions)
            root_progress = len(root_funcs_processed) + 1
            progress_info = (
                f"({root_progress}/{total_roots})" if total_roots > 0 else ""
            )
        else:
            # Recursively evaluated child node: show (current root function index/total root functions, total evaluated nodes)
            root_progress = len(root_funcs_processed)
            if total_roots > 0:
                progress_info = (
                    f"({root_progress}/{total_roots}, total evaluated={total_evaluated})"
                )
            else:
                progress_info = f"(total evaluated={total_evaluated})"
        PrettyOutput.auto_print(
            f"[c2rust-library] {progress_info} evaluating: {label} (ID: {fid}), subtree function count={len(desc)}"
        )

        # Perform the LLM evaluation
        res = llm_evaluate_subtree(
            fid,
            desc,
            by_id,
            adj_func,
            disabled_norm,
            disabled_display,
            model_available,
            new_model,
            additional_notes,
        )
        eval_counter += 1
        processed_roots.add(fid)
        if is_root_func:
            root_funcs_processed.add(fid)
        res["mode"] = "llm"

        # Update the checkpoint
        checkpoint_state = create_checkpoint_state(
            checkpoint_key,
            eval_counter,
            processed_roots,
            pruned_dynamic,
            selected_roots,
        )
        last_ckpt_saved = periodic_checkpoint_save(
            ckpt_path,
            checkpoint_state,
            eval_counter,
            last_ckpt_saved,
            checkpoint_interval,
            resume,
        )

        # If replaceable, print a summary of the evaluation result (library/reference API/confidence/notes) and immediately mark descendants for pruning and subsequent skipping
        try:
            if res.get("replaceable") is True:
                libs = res.get("libraries") or (
                    [res.get("library")] if res.get("library") else []
                )
                libs = [str(x) for x in libs if str(x)]
                api = str(res.get("api") or "")
                apis = res.get("apis")
                notes = str(res.get("notes") or "")
                conf = res.get("confidence")
                try:
                    conf = float(conf) if conf is not None else 0.0
                except Exception:
                    conf = 0.0
                libs_str = ", ".join(libs) if libs else "(no library specified)"
                apis_str = (
                    ", ".join([str(a) for a in apis])
                    if isinstance(apis, list)
                    else (api if api else "")
                )
                # Compute progress: distinguish initial root functions from recursively evaluated child nodes
                total_roots = len(root_funcs)
                if is_root_func:
                    # Initial root function: show (current root function index/total root functions)
                    root_progress = len(root_funcs_processed)
                    progress_info = (
                        f"({root_progress}/{total_roots})" if total_roots > 0 else ""
                    )
                else:
                    # Recursively evaluated child node: show (current root function index/total root functions, total evaluated nodes)
                    root_progress = len(root_funcs_processed)
                    total_evaluated = len(processed_roots)
                    if total_roots > 0:
                        progress_info = (
                            f"({root_progress}/{total_roots}, total evaluated={total_evaluated})"
                        )
                    else:
                        progress_info = f"(total evaluated={total_evaluated})"
                msg = f"[c2rust-library] {progress_info} replaceable: {label} -> library: {libs_str}"
                if apis_str:
                    msg += f"; reference API: {apis_str}"
                msg += f"; confidence: {conf:.2f}"
                if notes:
                    msg += f"; notes: {notes[:MAX_NOTES_DISPLAY_LENGTH]}"
                PrettyOutput.auto_print(msg)

                # If a node is replaceable, do not evaluate its child nodes regardless of whether it is ultimately replaced (such as entry function protection)
                # Entry function protection: do not replace main (keep it for transpilation), but its child nodes need to be pruned (because the functionality can be implemented by the library)
                # Immediate pruning (excluding the root): prune child nodes as long as the node is replaceable, whether or not it is an entry function
                to_prune = set(desc)
                to_prune.discard(fid)

                newly = len(to_prune - pruned_dynamic)
                pruned_dynamic.update(to_prune)

                # Mark whether it is an entry function, used in the later output stage to decide whether to modify the ref field
                is_entry = is_entry_function(rec_meta)
                if is_entry:
                    res["is_entry_function"] = True
                    PrettyOutput.auto_print(
                        f"[c2rust-library] Entry function protection: {label} is kept for transpilation (ref not modified), but its child nodes are pruned (the functionality can be implemented by the library)."
                        f"The replacement information will be recorded in library_replacements.jsonl for transpilation reference."
                    )
                else:
                    res["is_entry_function"] = False

                # Whether or not it is an entry function, add it to selected_roots (the replacement information of entry functions needs to be recorded for transpilation reference)
                selected_roots.append((fid, res))

                # Update the checkpoint
                checkpoint_state = create_checkpoint_state(
                    checkpoint_key,
                    eval_counter,
                    processed_roots,
                    pruned_dynamic,
                    selected_roots,
                )
                last_ckpt_saved = periodic_checkpoint_save(
                    ckpt_path,
                    checkpoint_state,
                    eval_counter,
                    last_ckpt_saved,
                    checkpoint_interval,
                    resume,
                )

                PrettyOutput.auto_print(
                    f"[c2rust-library] Immediately marked child nodes for pruning (newly added this time): +{newly} (cumulative={len(pruned_dynamic)})"
                )
                # Note: whether or not it is an entry function, as long as replaceable is True, do not evaluate child nodes
            else:
                # If not replaceable, continue evaluating its child nodes (depth-first)
                for ch in adj_func.get(fid, []):
                    evaluate_node(ch, is_root_func=False)
        except Exception as e:
            PrettyOutput.auto_print(
                f"[c2rust-library] Error while evaluating node {fid} ({label}): {e}"
            )
            # Even on error, mark it as processed to avoid an infinite loop
            processed_roots.add(fid)
            if is_root_func:
                root_funcs_processed.add(fid)

    # Evaluate each candidate root; if a root is non-replaceable, recursively evaluate its child nodes
    for fid in root_funcs:
        evaluate_node(fid, is_root_func=True)

    # The pruning set comes from the accumulated results of the dynamic evaluation stage
    pruned_funcs: Set[int] = set(pruned_dynamic)
    # If candidate roots (candidates) are specified, delete unreachable functions as well
    try:
        pruned_funcs.update(scope_unreachable_funcs)
    except Exception as e:
        save_exception(
            e, module="haijunbot_c2rust.library_replacer", function="evaluate_node"
        )
        pass

    # Write the new symbol table
    replacements = write_output_symbols(
        all_records,
        pruned_funcs,
        selected_roots,
        out_symbols_path,
        out_symbols_prune_path,
    )

    # Write the replacement mapping
    with open(out_mapping_path, "w", encoding="utf-8") as fm:
        if replacements:
            for m in replacements:
                fm.write(json.dumps(m, ensure_ascii=False) + "\n")
        else:
            # Even if there are no replacements, record statistics to help debugging
            summary = {
                "summary": {
                    "total_evaluated": eval_counter,
                    "total_processed_roots": len(processed_roots),
                    "total_selected_roots": len(selected_roots),
                    "total_pruned_funcs": len(pruned_funcs),
                    "note": "No replaceable functions were found. Possible reasons: 1) all functions are non-replaceable; 2) all replaceable functions are entry functions (protected); 3) selected_roots is empty when restoring from a checkpoint.",
                }
            }
            fm.write(json.dumps(summary, ensure_ascii=False) + "\n")
            PrettyOutput.auto_print(
                f"[c2rust-library] Warning: no replaceable functions were found; library_replacements.jsonl contains only statistics."
                f"evaluated={eval_counter}, processed roots={len(processed_roots)}, selected replaceable roots={len(selected_roots)}"
            )

    # Generate the translation order (pruning stage and alias)
    order_path = None
    try:
        compute_translation_order_jsonl(
            Path(out_symbols_path), out_path=order_prune_path
        )
        shutil.copy2(order_prune_path, alias_order_path)
        order_path = alias_order_path
    except Exception as e:
        PrettyOutput.auto_print(f"[c2rust-library] Failed to generate the translation order from the pruned symbol table: {e}")

    # Clean up the checkpoint after completion (optional)
    try:
        if resume and clear_checkpoint_on_done and ckpt_path.exists():
            ckpt_path.unlink()
            PrettyOutput.auto_print(f"[c2rust-library] Cleaned up checkpoint file: {ckpt_path}")
    except Exception as e:
        save_exception(
            e, module="haijunbot_c2rust.library_replacer", function="evaluate_node"
        )
        pass

    PrettyOutput.auto_print(
        "[c2rust-library] Library replacement pruning complete (LLM subtree evaluation):\n"
        f"- Selected replaceable roots: {len(selected_roots)}\n"
        f"- Pruned functions: {len(pruned_funcs)}\n"
        f"- New symbol table: {out_symbols_path}\n"
        f"- Replacement mapping: {out_mapping_path}\n"
        f"- Compatibility symbol table output: {out_symbols_prune_path}\n"
        + (f"- Translation order: {order_path}\n" if order_path else "")
        + f"- Compatibility order output: {order_prune_path}"
    )

    result: Dict[str, Path] = {
        "symbols": Path(out_symbols_path),
        "mapping": Path(out_mapping_path),
        "symbols_prune": Path(out_symbols_prune_path),
    }
    if order_path:
        result["order"] = Path(order_path)
    if order_prune_path:
        result["order_prune"] = Path(order_prune_path)
    return result


__all__ = ["apply_library_replacement"]
