# -*- coding: utf-8 -*-
"""
HaijunBot Security Analysis Suite

Current version overview:
- Critical path: direct scan (direct_scan) -> single-Agent one-by-one verification (read-only tools: read_code/execute_script) -> aggregated output (JSON + Markdown)
- Target scope: identification of basic security issues such as memory management, buffer operations, and error handling
- Constraints: do not modify core framework files, keep intrusiveness minimal; strictly read-only analysis

Integration approach:
- Reuse haijunbot.haijunbot_agent.Agent and the tool registration system (haijunbot.haijunbot_tools.registry.ToolRegistry)
- Entry points provided:
  - run_security_analysis(entry_path, ...): direct scan + single-Agent one-by-one verification + aggregation

  - workflow.direct_scan(entry_path, ...): heuristic direct scan only

Description:
- MultiAgent orchestration and related prompts have been removed; there is no notion of a "phase one"
- Modular refactoring: functionality has been split into multiple modules (prompts, parsers, utils, agents, clustering, analysis, verification, review)
"""

from haijunbot.haijunbot_utils.exception_utils import save_exception
from typing import Any, Dict, List, Optional

from haijunbot.haijunbot_utils.output import PrettyOutput

from haijunbot.haijunbot_agent import Agent  # noqa: F401
from haijunbot.haijunbot_sec.utils import (
    initialize_analysis_context as _initialize_analysis_context,
)
from haijunbot.haijunbot_sec.utils import (
    load_or_run_heuristic_scan as _load_or_run_heuristic_scan,
)
from haijunbot.haijunbot_sec.utils import prepare_candidates as _prepare_candidates
from haijunbot.haijunbot_sec.utils import (
    group_candidates_by_file as _group_candidates_by_file,
)
from haijunbot.haijunbot_sec.utils import create_report_writer as _create_report_writer
from haijunbot.haijunbot_sec.clustering import (  # type: ignore[attr-defined]
    process_clustering_phase as _process_clustering_phase,
)
from haijunbot.haijunbot_sec.verification import (
    process_verification_phase as _process_verification_phase,
)

from haijunbot.haijunbot_sec.workflow import direct_scan
from haijunbot.haijunbot_sec.workflow import run_with_agent

# Note: The current version does not use MultiAgent orchestration; the default multi-agent configuration and creation functions have been removed.
# Please use run_security_analysis (single-Agent one-by-one verification) or workflow.direct_scan + format_markdown_report (direct scan baseline).
# Note: Some functions have been migrated to modular files (prompts.py, parsers.py, utils.py, agents.py, clustering.py, analysis.py, verification.py, review.py);
# this file retains alias imports of these functions for backward compatibility.


def run_security_analysis(
    entry_path: str,
    languages: Optional[List[str]] = None,
    report_file: Optional[str] = None,
    cluster_limit: int = 50,
    exclude_dirs: Optional[List[str]] = None,
    enable_verification: bool = True,
    force_save_memory: bool = False,
    output_file: Optional[str] = None,
) -> str:
    """
    Run the security analysis workflow (hybrid mode).

    Improvements:
    - Even in agent mode, first perform a local regex/heuristic direct scan to generate candidate issues;
      then split the candidate issues into subtasks and hand them to multiple Agents for in-depth analysis and aggregation.

    Note: This function will update the status file to the error state when an exception occurs.

    Parameters:
    - entry_path: Root directory path to be analyzed
    - languages: Restrict the language extensions to scan (e.g. ["c", "cpp", "h", "hpp", "rs"]); if empty, use the default

    Returns:
    - Final report (string), generated by the Aggregator (JSON + Markdown)

    Others:
    - report_file: Incremental report file path (JSONL). When each subtask detects issues, a record is immediately appended to this file;
      if not specified, it is written by default to entry_path/.haijunbot/sec/agent_issues.jsonl
    - cluster_limit: Maximum number of warnings processed per batch during clustering (default 50); when a single file has too many warnings, clustering is done in batches
    - exclude_dirs: List of directories to exclude (optional); by default it already includes test directories (test, tests, __tests__, spec, testsuite, testdata)
    - enable_verification: Whether to enable secondary verification (default True); when disabled, issues confirmed by the analysis Agent are written directly to the report
    - Resumable scan: enabled by default. State is restored based on the .haijunbot/sec/candidates.jsonl, clusters.jsonl, and analysis.jsonl files.
    """

    langs = languages or ["c", "cpp", "h", "hpp", "rs"]

    # Status manager (no longer using status.json, using an empty object)
    class DummyStatusManager:
        def update_pre_scan(self, **kwargs: Any) -> None:
            pass

        def update_clustering(self, **kwargs: Any) -> None:
            pass

        def update_review(self, **kwargs: Any) -> None:
            pass

        def update_verification(self, **kwargs: Any) -> None:
            pass

        def mark_completed(self, **kwargs: Any) -> None:
            pass

        def mark_error(self, **kwargs: Any) -> None:
            pass

    status_mgr = DummyStatusManager()

    # Initialize the analysis context
    sec_dir, progress_path, _progress_append = _initialize_analysis_context(
        entry_path, status_mgr
    )

    # 1) Heuristic scan (supports resumable scan)
    candidates, summary = _load_or_run_heuristic_scan(
        entry_path, langs, exclude_dirs, sec_dir, status_mgr, _progress_append
    )

    # 2) Condense the candidate issues into a subtask list, controlling the context length
    compact_candidates = _prepare_candidates(candidates)

    # 3) Save the candidates to a new candidates.jsonl file (including gid)
    from haijunbot.haijunbot_sec.file_manager import get_candidates_file
    from haijunbot.haijunbot_sec.file_manager import save_candidates

    try:
        save_candidates(sec_dir, compact_candidates)
        _progress_append(
            {
                "event": "candidates_saved",
                "path": str(get_candidates_file(sec_dir)),
                "issues_count": len(compact_candidates),
            }
        )
    except Exception as e:
        save_exception(e, module="haijunbot_sec.__init__", function="mark_error")
        pass

    # Record batch selection information (optional, for logging)
    try:
        groups = _group_candidates_by_file(compact_candidates)
        if groups:
            selected_file, items = max(groups.items(), key=lambda kv: len(kv[1]))
            try:
                PrettyOutput.auto_print(
                    f"[haijunbot-sec] Batch selection: file={selected_file} count={len(items)}"
                )
            except Exception as e:
                save_exception(e, module="haijunbot_sec.__init__", function="mark_error")
                pass
            _progress_append(
                {
                    "event": "batch_selection",
                    "selected_file": selected_file,
                    "selected_count": len(items),
                    "total_in_file": len(items),
                }
            )
    except Exception as e:
        save_exception(e, module="haijunbot_sec.__init__", function="mark_error")
        pass

    # Create the report writer function
    _append_report = _create_report_writer(sec_dir, report_file)

    # 3) Process the clustering phase
    cluster_batches, invalid_clusters_for_review = _process_clustering_phase(
        compact_candidates,
        entry_path,
        langs,
        cluster_limit,
        sec_dir,
        status_mgr,
        _progress_append,
        force_save_memory=force_save_memory,
    )

    # 4) Process the verification phase
    meta_records: List[Dict[str, Any]] = []
    all_issues = _process_verification_phase(
        cluster_batches,
        entry_path,
        langs,
        sec_dir,
        status_mgr,
        _progress_append,
        _append_report,
        enable_verification=enable_verification,
        force_save_memory=force_save_memory,
    )

    # 5) Use the unified aggregator to generate the final report (JSON + Markdown)
    try:
        from haijunbot.haijunbot_sec.report import build_json_and_markdown

        result = build_json_and_markdown(
            all_issues,  # type: ignore
            scanned_root=summary.get("scanned_root"),
            scanned_files=summary.get("scanned_files"),
            meta=meta_records or None,
            output_file=output_file,
        )
        # Mark the analysis as completed
        status_mgr.mark_completed(
            total_issues=len(all_issues),
            message=f"Security analysis completed, {len(all_issues)} issues found in total",
        )
        return result
    except Exception as e:
        # Update the status when an error occurs
        error_msg = str(e)
        status_mgr.mark_error(error_message=error_msg, error_type=type(e).__name__)
        raise
    finally:
        # Clean up resources
        pass


__all__ = [
    "run_security_analysis",
    "direct_scan",
    "run_with_agent",
]
