# -*- coding: utf-8 -*-
"""Issue #94 regression tests: Plugin rule configN prefix and directory index misalignment.

Reproduction scenario: With multiple rules_load_dirs (plugin rule directories), the scanning side
get_all_available_rule_names used to label all config directories uniformly as config0:,
while the parsing side mapped to _get_all_rules_dirs() index via hardcoded offset target_idx = 2 + config_num,
causing rule names like config0:gh.md to not be correctly resolved by get_named_rule / get_rule_file_path.

After fix: Scanning side generates configN based on rules_dirs actual index (N>=1,
rules_dirs[0] is global directory using global: prefix), parsing side directly based on
rules_dirs index, scanning and parsing strictly aligned.
"""

import os
from pathlib import Path

from haijunbot.haijunbot_agent.rules_manager import RulesManager
from haijunbot.haijunbot_utils.config import set_global_config_data


def _make_rule(dir_path: Path, name: str, description: str) -> None:
    """Write a rule file with YAML Front Matter in the specified directory."""
    dir_path.mkdir(parents=True, exist_ok=True)
    (dir_path / f"{name}.md").write_text(
        f"---\nname: {name}\ndescription: {description}\n---\n# {name}\n",
        encoding="utf-8",
    )


def test_config_prefix_generation_and_resolution(tmp_path, monkeypatch):
    """configN prefix generation and resolution are consistent across multiple config directories, rules load correctly."""
    monkeypatch.setenv("HAIJUNBOT_DATA_DIR", str(tmp_path / "data"))
    (tmp_path / "data").mkdir(parents=True, exist_ok=True)

    # Project rule directory
    project_dir = tmp_path / "proj"
    project_rules = project_dir / ".haijunbot" / "rules"
    _make_rule(project_rules, "proj_rule", "Project rule")

    # Two plugin rule directories (simulating multiple rules_load_dirs)
    plugin_a = tmp_path / "plugins" / "plugin-a" / "rules"
    plugin_b = tmp_path / "plugins" / "plugin-b" / "rules"
    _make_rule(plugin_a, "alpha", "Plugin A rule")
    _make_rule(plugin_b, "beta", "Plugin B rule")

    set_global_config_data({"rules_load_dirs": [str(plugin_a), str(plugin_b)]})

    rm = RulesManager(str(project_dir))

    # 1) Scanning side: config prefix generated by rules_dirs actual index (config1/config2)
    files = rm.get_all_available_rule_names()["files"]
    alpha_name = next(n for n in files if n.endswith("alpha.md"))
    beta_name = next(n for n in files if n.endswith("beta.md"))
    assert alpha_name == "config1:alpha.md", f"Plugin A should be labeled config1, got {alpha_name}"
    assert beta_name == "config2:beta.md", f"Plugin B should be labeled config2, got {beta_name}"

    # 2) Parsing side: get_named_rule can correctly load configN rules (returned None before fix)
    for name in (alpha_name, beta_name):
        assert rm.get_named_rule(name) is not None, f"get_named_rule({name}) returned None"

    # 3) get_rule_file_path returns real existing file path
    for name, expect_dir in ((alpha_name, plugin_a), (beta_name, plugin_b)):
        path = rm.get_rule_file_path(name)
        assert path != "--", f"get_rule_file_path({name}) returned --"
        assert os.path.isfile(path), f"get_rule_file_path({name}) = {path} is not a valid file"
        assert Path(path).parent == expect_dir, f"{name} path misaligned: {path}"

    # 4) load_rule works end-to-end
    assert rm.load_rule(alpha_name)
    assert rm.load_rule(beta_name)


def test_config_prefix_works_without_central_and_project(tmp_path, monkeypatch):
    """configN prefix still resolves correctly without central/project directories (regression of old offset assumption)."""
    monkeypatch.setenv("HAIJUNBOT_DATA_DIR", str(tmp_path / "data"))
    (tmp_path / "data").mkdir(parents=True, exist_ok=True)

    plugin_a = tmp_path / "plugins" / "plugin-a" / "rules"
    _make_rule(plugin_a, "alpha", "Plugin A rule")

    set_global_config_data({"rules_load_dirs": [str(plugin_a)]})

    # Project directory has no .haijunbot/rules, no central either
    rm = RulesManager(str(tmp_path / "empty_proj"))

    files = rm.get_all_available_rule_names()["files"]
    alpha_name = next(n for n in files if n.endswith("alpha.md"))
    assert alpha_name == "config1:alpha.md", f"Should be labeled config1, got {alpha_name}"
    assert rm.get_named_rule(alpha_name) is not None
    assert os.path.isfile(rm.get_rule_file_path(alpha_name))


def test_unknown_config_num_returns_none(tmp_path, monkeypatch):
    """Out-of-bounds configN prefix returns None, no exception."""
    monkeypatch.setenv("HAIJUNBOT_DATA_DIR", str(tmp_path / "data"))
    (tmp_path / "data").mkdir(parents=True, exist_ok=True)
    set_global_config_data({"rules_load_dirs": []})

    rm = RulesManager(str(tmp_path / "proj"))
    assert rm.get_named_rule("config99:gh.md") is None
    assert rm.get_rule_file_path("config99:gh.md") == "--"
